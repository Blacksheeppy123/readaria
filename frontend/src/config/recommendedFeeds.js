/**
 * Helper: get favicon URL from feed URL
 */
export function getFaviconUrl(feedUrl, size = 32) {
  try {
    const url = new URL(feedUrl)
    return `https://www.google.com/s2/favicons?domain=${url.hostname}&sz=${size}`
  } catch {
    return null
  }
}


